#!/bin/sh
# Builds the browser mock of the twins' panel: the firmware's own UI files, compiled to WebAssembly,
# into `docs/mocks/jpanel-s3/sim.wasm`. See `README.md` here.
#
# The toolchain is the system clang (any with the wasm32 target — Ubuntu's clang 18 has it), plus
# three pinned downloads cached under ~/.cache/jbrain-wasm: wasi-libc's sysroot and compiler-rt's
# builtins from wasi-sdk 24, and binaryen's wasm-opt, which adds Asyncify — the transform that
# lets the C loop stop every frame and hand the browser its turn.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
fw=$(dirname "$here")
repo=$(dirname "$fw")
out="${1:-$repo/docs/mocks/jpanel-s3/sim.wasm}"
cache="${JBRAIN_WASM_CACHE:-$HOME/.cache/jbrain-wasm}"
sdk=https://github.com/WebAssembly/wasi-sdk/releases/download/wasi-sdk-24
mkdir -p "$cache"

fetch() { # name url sha256
    if [ ! -f "$cache/$1" ]; then
        curl -sSfL --retry 4 -o "$cache/$1.part" "$2"
        mv "$cache/$1.part" "$cache/$1"
    fi
    echo "$3  $cache/$1" | sha256sum -c --quiet -
}
fetch wasi-sysroot-24.0.tar.gz "$sdk/wasi-sysroot-24.0.tar.gz" \
    35172f7d2799485b15a46b1d87f50a585d915ec662080f005d99153a50888f08
fetch builtins-24.0.tar.gz "$sdk/libclang_rt.builtins-wasm32-wasi-24.0.tar.gz" \
    7e33c0df758b90469b1de3ca158e2d0a7f71934d5884525ba6a372de0b3b0ec7
[ -d "$cache/wasi-sysroot-24.0" ] || tar -xzf "$cache/wasi-sysroot-24.0.tar.gz" -C "$cache"
[ -d "$cache/libclang_rt.builtins-wasm32-wasi-24.0" ] || tar -xzf "$cache/builtins-24.0.tar.gz" -C "$cache"
if [ ! -x "$cache/node_modules/.bin/wasm-opt" ]; then
    (cd "$cache" && npm install --silent --no-save --prefix "$cache" binaryen@123.0.0 >/dev/null)
fi

# The cue names, in enum order, straight from the header so they cannot drift.
gen=$(mktemp -d)
trap 'rm -rf "$gen"' EXIT
{
    echo '/* Generated by build.sh from cue.h. */'
    echo 'static const char *const CUE_NAMES[CUE_COUNT] = {'
    sed -n '/typedef enum {/,/} cue_t;/p' "$fw/main/cue.h" | grep -oE '^[[:space:]]+CUE_[A-Z0-9_]+' |
        tr -d ' \t' | grep -v '^CUE_COUNT$' | sed 's/^CUE_\(.*\)/    [CUE_\1] = "\1",/'
    echo '};'
} >"$gen/cue_names.gen.h"

src="$fw/main/jpanel_core.c $fw/main/stream.c $fw/main/panel_sm.c $fw/main/cue.c $fw/main/ring.c
     $fw/main/reach.c $fw/main/confirm.c $fw/main/face.c $fw/main/font.c $fw/main/emotion.c
     $fw/main/rig.c $fw/main/gesture.c $fw/main/overlay.c $fw/main/caption.c $fw/main/screen.c $fw/main/poop.c $fw/main/tickle.c $fw/main/game.c $fw/main/jet.c
     $fw/main/orient.c"
# shellcheck disable=SC2086
"${CLANG:-clang}" --target=wasm32-wasi --sysroot="$cache/wasi-sysroot-24.0" -std=gnu11 -O2 \
    -Wall -Wextra -Werror -Wno-unused-function -I"$fw/main" -I"$fw/host" -I"$gen" \
    -D_WASI_EMULATED_PTHREAD -mexec-model=reactor -nodefaultlibs \
    -Wl,--no-entry -Wl,--export=malloc -Wl,--initial-memory=67108864 \
    -o "$gen/sim.wasm" "$here/sim.c" $src \
    -lc "$cache/libclang_rt.builtins-wasm32-wasi-24.0/libclang_rt.builtins-wasm32.a"
mkdir -p "$(dirname "$out")"
"$cache/node_modules/.bin/wasm-opt" -O2 --asyncify --pass-arg=asyncify-imports@env.js_frame \
    "$gen/sim.wasm" -o "$out"
echo "built $out ($(wc -c <"$out") bytes)"
