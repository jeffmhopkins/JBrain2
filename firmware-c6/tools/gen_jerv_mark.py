#!/usr/bin/env python3
"""Rasterises the PWA's icon mark into the A8 images the panel draws Jerv with.

    python3 firmware-c6/tools/gen_jerv_mark.py            # rewrite components/ui_kit/ui_jerv_mark.c
    python3 firmware-c6/tools/gen_jerv_mark.py --check    # exit 1 if the checked-in file is stale

The source is `frontend/public/favicon.svg` — the neuron mark: a centre disc, branching strokes
with round caps and joins, terminal dots — read for its geometry, never redrawn by hand (owner,
2026-10-12: Jerv uses "the PWA's actual icon in the PWA's blue"). Only the mark is taken; the
`#15171A` rounded square behind it is the PWA's, and the panel puts the mark on its own tinted
disc. The output is an alpha mask (LV_COLOR_FORMAT_A8) per glyph size the panel draws, recoloured
at runtime, so one mask serves any colour and the tile and the header each get pixels cut for
their size rather than a scaled copy.

Deterministic: plain Python, no dependencies, a fixed 8 x 8 supersample per pixel and integer
rounding, so the same SVG always makes the same bytes. The checked-in C file is what the build
compiles (no generation step in the build), so two clean builds stay byte-identical; CI and
`--check` catch a file that no longer matches the SVG.
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "frontend" / "public" / "favicon.svg"
OUT = ROOT / "firmware-c6" / "components" / "ui_kit" / "ui_jerv_mark.c"
VIEWBOX = 64.0
#: The glyph box `ui_icon` gives a disc (disc_px * 52 / 96): the home tile's 96 px disc and the
#: header's 44 px one.
SIZES = (52, 23)
SS = 8


def geometry(svg: str) -> tuple[list[tuple[float, float, float, float]], float, list[tuple[float, float, float]]]:
    stroke = re.search(r'stroke-width="([\d.]+)"', svg)
    assert stroke, "no stroke-width in the mark"
    segments = []
    for d in re.findall(r'<path d="([^"]+)"', svg):
        nums = [float(x) for x in re.findall(r"-?[\d.]+", d)]
        assert d.strip().startswith("M") and len(nums) % 2 == 0 and len(nums) >= 4, d
        pts = list(zip(nums[0::2], nums[1::2], strict=True))
        segments += [(a[0], a[1], b[0], b[1]) for a, b in zip(pts, pts[1:], strict=False)]
    circles = [
        (float(cx), float(cy), float(r))
        for cx, cy, r in re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"', svg)
    ]
    assert segments and circles, "the mark's strokes and dots"
    return segments, float(stroke.group(1)), circles


def inside(x: float, y: float, segs: list, half: float, circles: list) -> bool:
    for cx, cy, r in circles:
        if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
            return True
    for x1, y1, x2, y2 in segs:
        dx, dy = x2 - x1, y2 - y1
        t = ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)
        t = 0.0 if t < 0 else 1.0 if t > 1 else t
        if math.hypot(x - (x1 + t * dx), y - (y1 + t * dy)) <= half:
            return True
    return False


def raster(size: int, segs: list, stroke: float, circles: list) -> bytes:
    scale = VIEWBOX / size
    out = bytearray()
    for py in range(size):
        for px in range(size):
            hits = 0
            for sy in range(SS):
                for sx in range(SS):
                    x = (px + (sx + 0.5) / SS) * scale
                    y = (py + (sy + 0.5) / SS) * scale
                    hits += inside(x, y, segs, stroke / 2, circles)
            out.append((hits * 255 + (SS * SS) // 2) // (SS * SS))
    return bytes(out)


def render() -> str:
    segs, stroke, circles = geometry(SVG.read_text(encoding="utf-8"))
    parts = [
        "/* GENERATED by firmware-c6/tools/gen_jerv_mark.py from frontend/public/favicon.svg — do\n"
        " * not edit. The PWA's mark as A8 alpha masks, one per glyph size; ui_icon recolours them\n"
        " * (UI_C_JERV, the PWA's #7FA7C9). */\n",
        '#include "ui_jerv_mark.h"\n',
    ]
    for size in SIZES:
        data = raster(size, segs, stroke, circles)
        rows = ",\n".join(
            "    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)
        )
        parts.append(
            f"\nstatic const uint8_t MARK_{size}[{len(data)}] = {{\n{rows},\n}};\n"
            f"\nconst lv_image_dsc_t ui_jerv_mark_{size} = {{\n"
            f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {size},"
            f" .h = {size}, .stride = {size}}},\n"
            f"    .data_size = sizeof MARK_{size},\n"
            f"    .data = MARK_{size},\n"
            "};\n"
        )
    return "".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run firmware-c6/tools/gen_jerv_mark.py", file=sys.stderr)
            return 1
        print("ui_jerv_mark.c matches favicon.svg")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
